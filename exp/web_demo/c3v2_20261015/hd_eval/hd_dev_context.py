"""Generate assistant context for HumDial dev items (dev audio has user speech only).

For each non-clean dev item, the assistant reply that is playing when the target utterance
arrives is generated by the production response prompt on Omni (text only, temperature 0).
Writes dev_context.json next to this file. Resumable.

Layout per scenario (sentence.json speech_segments):
  interruption / backchannel / Silence / Third-party_after: [question, target]  -> playing
  Speech Directed at Others: [q1, q2, target]                                    -> playing (reply to q2)
  Third-party Speech_before: [third-party, question]                             -> listening, whole clip
  Pause Handling: [question with pause]                                           -> listening
"""
import asyncio
import json
import os
import sys
from pathlib import Path

ROOT = Path('/root/autodl-tmp/fd-badcat-c3v2')
for k in ('http_proxy', 'https_proxy', 'HTTP_PROXY', 'HTTPS_PROXY', 'all_proxy', 'ALL_PROXY'):
    os.environ.pop(k, None)
os.environ.setdefault('NO_PROXY', '127.0.0.1,localhost')
os.environ.setdefault('FDBC_QWEN_URL', 'http://127.0.0.1:10003/v1/chat/completions')
sys.path.insert(0, str(ROOT / 'src'))
import yaml
import module

HERE = Path(__file__).resolve().parent
DEV = Path('/root/autodl-tmp/HumDial_train/HD-Track2/HD-Track2-dev')
OUT = HERE / 'dev_context.json'
cfg = yaml.safe_load((ROOT / 'src/config.yaml').read_text(encoding='utf-8'))
demo = yaml.safe_load((ROOT / 'configs/demo_chat.yaml').read_text(encoding='utf-8'))
PROMPT = (demo.get('prompts') or {}).get('response') or cfg['prompts']['response']


async def reply(history):
    messages = [{'role': 'system', 'content': PROMPT}] + history
    text = ''.join([p async for p in module.llm_qwen3o_stream(messages, max_tokens=256)])
    return text.strip()


def jobs():
    for lang in ('zh', 'en'):
        root = DEV / f'HD-Track2-dev-{lang}'
        for folder in sorted(p for p in root.iterdir() if p.is_dir()):
            cat = folder.name
            for meta in sorted(folder.glob('*_sentence.json')):
                if meta.name.startswith('clean'):
                    continue
                wav = meta.with_name(meta.name.replace('_sentence.json', '.wav'))
                if not wav.exists():
                    continue
                segs = [s for s in json.loads(meta.read_text())['speech_segments'] if s['text'].strip()]
                stem = wav.stem
                yield f'{lang}|{cat}|{stem}', lang, cat, stem, wav, segs


async def build(key, lang, cat, stem, wav, segs):
    base = {'lang': lang, 'category': cat, 'stem': stem, 'wav': str(wav)}
    if cat == 'Pause Handling':
        s = segs[0]
        return {**base, 'playing': False, 'target_seg': [s['xmin'], s['xmax']], 'target_text': s['text'],
                'previous_user': '', 'assistant_text': ''}
    if cat == 'Third-party Speech_before':
        if len(segs) < 2:
            return None
        return {**base, 'playing': False, 'target_seg': [segs[0]['xmin'], segs[-1]['xmax']],
                'target_text': ' || '.join(s['text'] for s in segs),
                'second_start_rel': segs[-1]['xmin'] - segs[0]['xmin'],
                'previous_user': '', 'assistant_text': ''}
    if len(segs) < 2:
        return None
    if cat == 'Speech Directed at Others' and len(segs) >= 3:
        a0 = await reply([{'role': 'user', 'content': segs[0]['text']}])
        hist = [{'role': 'user', 'content': segs[0]['text']}, {'role': 'assistant', 'content': a0},
                {'role': 'user', 'content': segs[-2]['text']}]
        prev = segs[-2]['text']
    else:
        hist = [{'role': 'user', 'content': segs[0]['text']}]
        prev = segs[0]['text']
    ans = await reply(hist)
    t = segs[-1]
    return {**base, 'playing': True, 'target_seg': [t['xmin'], t['xmax']], 'target_text': t['text'],
            'previous_user': prev, 'assistant_text': ans}


async def main():
    done = json.loads(OUT.read_text(encoding='utf-8')) if OUT.exists() else {}
    todo = [j for j in jobs() if j[0] not in done]
    print('todo', len(todo), 'done', len(done), flush=True)
    sem = asyncio.Semaphore(int(os.environ.get('CONC', '6')))

    async def one(j):
        async with sem:
            for attempt in range(3):
                try:
                    r = await build(*j)
                    break
                except Exception as exc:
                    r = None
                    print('retry', j[0], type(exc).__name__, exc, flush=True)
                    await asyncio.sleep(2)
            if r is not None:
                done[j[0]] = r
    for i in range(0, len(todo), 60):
        await asyncio.gather(*(one(j) for j in todo[i:i + 60]))
        OUT.write_text(json.dumps(done, ensure_ascii=False, indent=0), encoding='utf-8')
        print('saved', len(done), flush=True)


asyncio.run(main())
